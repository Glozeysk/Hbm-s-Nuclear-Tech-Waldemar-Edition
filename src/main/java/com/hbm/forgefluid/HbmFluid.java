package com.hbm.forgefluid;

import java.awt.Color;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import com.hbm.forgefluid.FluidTypeHandler.FluidProperties;
import com.hbm.forgefluid.FluidTypeHandler.FluidTrait;
import com.hbm.inventory.EngineRecipes;
import com.hbm.inventory.EngineRecipes.FuelGrade;
import com.hbm.inventory.FluidCombustionRecipes;
import com.hbm.lib.RefStrings;
import com.hbm.render.misc.EnumSymbol;

import net.minecraft.client.renderer.texture.TextureMap;
import net.minecraft.util.ResourceLocation;
import net.minecraftforge.fluids.Fluid;
import net.minecraftforge.fluids.FluidRegistry;

/**
 * Declarative fluid definition. Everything about a fluid - registry name, translation key, textures, color,
 * temperature, hazard card, flag and valued traits, engine fuel - is stated once through the fluent builder.
 * All registration (Forge fluid registry, hazard properties, combustion, engine fuel) is generated by iterating
 * {@link #ALL}, so adding a fluid never means editing several separate registry methods again.
 *
 * Valued traits are only stored when non-zero, so an omitted or zero characteristic is genuinely absent - e.g.
 * a fluid without a COMBUSTION_TU value never shows up as a combustion fuel at all.
 */
public class HbmFluid {

	public static final List<HbmFluid> ALL = new ArrayList<HbmFluid>();

	private final String name;
	private String translationKey;
	private String stillTexture;
	private String flowingTexture;
	private int color = 0xFFFFFF;
	private Integer temperature;
	private Integer density;
	private Integer viscosity;
	private Integer luminosity;

	private int poison = 0;
	private int flammability = 0;
	private int reactivity = 0;
	private float dfcFuel = 0;
	private EnumSymbol symbol = EnumSymbol.NONE;

	private final List<FluidTrait> flags = new ArrayList<FluidTrait>();
	private final Map<FluidTrait, Double> values = new HashMap<FluidTrait, Double>();

	private FuelGrade fuelGrade;
	private long fuelPower;

	private final Map<HbmFluidContainer, String> containers = new HashMap<HbmFluidContainer, String>();

	private Fluid fluid;

	private HbmFluid(String name) {
		this.name = name;
	}

	public static HbmFluid builder(String name) {
		return new HbmFluid(name);
	}

	public HbmFluid translationKey(String key) { this.translationKey = key; return this; }
	public HbmFluid textures(String still, String flowing) { this.stillTexture = still; this.flowingTexture = flowing; return this; }
	public HbmFluid color(int rgb) { this.color = rgb; return this; }
	public HbmFluid temperature(int celsius) { this.temperature = celsius + 273; return this; }
	public HbmFluid temperatureKelvin(int kelvin) { this.temperature = kelvin; return this; }
	public HbmFluid density(int d) { this.density = d; return this; }
	public HbmFluid viscosity(int v) { this.viscosity = v; return this; }
	public HbmFluid luminosity(int l) { this.luminosity = l; return this; }

	public HbmFluid props(int poison, int flammability, int reactivity, EnumSymbol symbol) {
		this.poison = poison;
		this.flammability = flammability;
		this.reactivity = reactivity;
		this.symbol = symbol;
		return this;
	}

	public HbmFluid dfc(float efficiency) { this.dfcFuel = efficiency; return this; }

	//flag trait (corrosive, amat, ...)
	public HbmFluid trait(FluidTrait trait) { flags.add(trait); return this; }
	//valued trait (combustion tu, rtg efficiency, ...); zero is dropped so it never counts as present
	public HbmFluid trait(FluidTrait trait, double value) { if(value != 0) values.put(trait, value); return this; }

	//engine (diesel/generator) fuel: grade + power; zero power = not a fuel
	public HbmFluid fuel(FuelGrade grade, long power) { this.fuelGrade = grade; this.fuelPower = power; return this; }

	//container membership: the model name (e.g. "canister_fuel") this fluid uses for that container item
	public HbmFluid canister(String model) { containers.put(HbmFluidContainer.CANISTER, model); return this; }
	public HbmFluid cell(String model) { containers.put(HbmFluidContainer.CELL, model); return this; }
	public HbmFluid gasCanister(String model) { containers.put(HbmFluidContainer.GAS_CANISTER, model); return this; }

	//Creates the Forge fluid (textures/lang by convention unless overridden) and enlists it. Assign the returned
	//Fluid to the existing ModForgeFluids static field so all current references keep working.
	public Fluid build() {
		String still = stillTexture != null ? stillTexture : "blocks/forgefluid/" + name + "_still";
		String flow = flowingTexture != null ? flowingTexture : "blocks/forgefluid/" + name + "_flowing";

		fluid = new Fluid(name,
				new ResourceLocation(RefStrings.MODID, still),
				new ResourceLocation(RefStrings.MODID, flow),
				new Color(color));

		if(temperature != null)
			fluid.setTemperature(temperature);
		if(density != null)
			fluid.setDensity(density);
		if(viscosity != null)
			fluid.setViscosity(viscosity);
		if(luminosity != null)
			fluid.setLuminosity(luminosity);
		if(translationKey != null)
			fluid.setUnlocalizedName(translationKey);

		for(Map.Entry<HbmFluidContainer, String> c : containers.entrySet())
			c.getKey().register(fluid, c.getValue());

		ALL.add(this);
		return fluid;
	}

	public Fluid getFluid() { return fluid; }

	// --- registration: called from the existing init hooks, generated from ALL ---

	public static void registerAllToForge() {
		for(HbmFluid f : ALL)
			if(!FluidRegistry.registerFluid(f.fluid))
				f.fluid = FluidRegistry.getFluid(f.name);
	}

	public static void applyAllProperties() {
		for(HbmFluid f : ALL) {
			FluidProperties p = new FluidProperties(f.poison, f.flammability, f.reactivity, f.dfcFuel, f.symbol,
					f.flags.toArray(new FluidTrait[0]));
			p.traitValues.putAll(f.values);
			FluidTypeHandler.registerProperties(f.fluid.getName(), p);
		}
	}

	//still/flowing icons for every builder fluid, so a new fluid never needs a manual registerSprite call
	public static void registerAllSprites(TextureMap map) {
		for(HbmFluid f : ALL) {
			map.registerSprite(f.fluid.getStill());
			map.registerSprite(f.fluid.getFlowing());
		}
	}

	public static void applyAllFuels() {
		for(HbmFluid f : ALL) {
			double tu = f.values.containsKey(FluidTrait.COMBUSTION_TU) ? f.values.get(FluidTrait.COMBUSTION_TU) : 0;
			if(tu > 0)
				FluidCombustionRecipes.addBurnableFluid(f.fluid, (int) tu);
			if(f.fuelGrade != null && f.fuelPower > 0)
				EngineRecipes.addFuel(f.fluid, f.fuelGrade, f.fuelPower);
		}
	}
}
